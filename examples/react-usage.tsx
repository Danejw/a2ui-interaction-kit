import * as React from 'react';
import {InteractiveItem} from '@danejw/a2ui-interaction-kit/react';
import '@danejw/a2ui-interaction-kit/react/styles.css';

/** A host application persists mutations and controls the displayed props. */
export function ExampleList() {
  const [items, setItems] = React.useState([
    {id: 'one', title: 'Review contractor shortlist', priority: false},
    {id: 'two', title: 'Inspect agent run', priority: false},
  ]);
  return <div style={{display: 'grid', gap: 12}}>
    {items.map(item => <InteractiveItem
      key={item.id}
      itemId={item.id}
      title={item.title}
      description="Agent task needs attention"
      details={<p>Details generated by the host app or A2UI.</p>}
      capabilities={['expandable','dismissible','prioritizable','actionable']}
      prioritized={item.priority}
      onDismiss={async () => {
        // Replace with your authorized API call. Update local state after success.
        setItems(existing => existing.filter(entry => entry.id !== item.id));
      }}
      onPrioritize={async () => {
        setItems(existing => existing.map(entry => entry.id === item.id ? {...entry, priority: !entry.priority} : entry));
      }}
      onActivate={() => window.alert(`Open ${item.title}`)}
    />)}
  </div>;
}
